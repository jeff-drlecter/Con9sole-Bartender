def text(member, authored: str) -> str:
    from features.language_preferences import language
    return text_for_code(language(member), authored)


def text_for_code(code: str, authored: str) -> str:
    if code != "tw":
        return authored
    if authored in TW:
        return TW[authored]
    for hk, tw in TW.items():
        if authored.endswith(hk) and len(authored) - len(hk) <= 4:
            return authored[:-len(hk)] + tw
    return authored


def view_copy(member, view):
    """Change display copy on a newly built view, never IDs, values or callbacks."""
    if not isinstance(view, (discord.ui.View, discord.ui.Modal)):
        return view
    originals = getattr(view, "_wording_originals", None)
    if originals is None:
        originals = view._wording_originals = {}
    for child in view.children:
        if isinstance(child, discord.ui.Button) and child.label:
            key = (id(child), "label")
            originals.setdefault(key, child.label)
            child.label = text(member, originals[key])
        elif isinstance(child, discord.ui.Select):
            if child.placeholder:
                key = (id(child), "placeholder")
                originals.setdefault(key, child.placeholder)
                child.placeholder = text(member, originals[key])
            for option in child.options:
                # Option labels can be game/member names: leave them unchanged.
                if option.description:
                    option.description = text(member, option.description)
        elif isinstance(child, discord.ui.TextInput):
            child.label = text(member, child.label)
            if child.placeholder:
                key = (id(child), "placeholder")
                originals.setdefault(key, child.placeholder)
                child.placeholder = text(member, originals[key])
    return view


def modal_copy(member, modal):
    modal.title = text(member, modal.title)
    view_copy(member, modal)
    return modal
